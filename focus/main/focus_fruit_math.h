// main/focus_fruit_math.h —— 计时页那只"会被一口口吃掉"的水果:序号、阶段与挑选规则。
//
// 本文件不引用 LVGL、ESP-IDF 或 FreeRTOS,只有几个纯函数,所以能用主机编译器直接
// 跑单元测试(tests/test_focus_fruit_math.c)。位图本身在 focus_sprites.*,
// 建对象、换图的是 focus_fruit.c。
//
// 水果是现成的像素画(6 种 × 5 个画好的阶段),不再由代码画形状;这里只管"画哪一只"
// 和"画到第几档"。像素数据由 tools/gen_sprites.py 从两张素材图切出来。
#pragma once

#include <stdint.h>

// ---------------------------------------------------------------------------
// 尺寸
// ---------------------------------------------------------------------------

// 六种水果:香蕉 / 西瓜 / 菠萝 / 番茄 / 胡萝卜 / 苹果。序号即下标,也是存档里
// fruit 字节的值,顺序不能随便动。
#define FOCUS_FRUIT_COUNT 6

// 每个水果五档,画好的:整只 / 一口 / 两口 / 三口 / 只剩一点。
#define FOCUS_FRUIT_STAGE_COUNT 5

// 果子的外接框边长。每张位图各自居中放进这个正方形,见 focus_fruit.c。
// 与 tools/gen_sprites.py 的 BOX 是同一个数:出图时按它缩放,上屏时按它居中。
#define FOCUS_FRUIT_BOX 134

// ---------------------------------------------------------------------------
// 接口(序号一律取模/夹住,不会越界读表)
// ---------------------------------------------------------------------------

// 纯 ASCII 名字,只给日志用(不渲染,故不进字库覆盖检查)。
const char *focus_fruit_name(uint8_t fruit);

// 按 rnd 挑一种水果,保证不等于 previous。previous 越界时只按 rnd 取。
// 调用方传 esp_random();把随机源留在调用方是为了让这个函数可在主机上复现。
uint8_t focus_fruit_pick(uint8_t previous, uint32_t rnd);

// 阶段已走过的千分数 -> 画第几档(0..FOCUS_FRUIT_STAGE_COUNT-1),单调不减。
// 五档均分:0-20% 整只,20-40% 一口,40-60% 两口,60-80% 三口,80-100% 只剩一点。
// 均分是有意的:每一档都停留得够久,不会出现"最后几分钟一直盯着同一个果核"。
// 想让它前慢后快,只改这一个函数。
uint8_t focus_fruit_permille_to_stage(int permille);
