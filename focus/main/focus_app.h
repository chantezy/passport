// main/focus_app.h —— 番茄钟的装配层。
//
// 把模型、界面、按键、落盘、提示音与电源策略缝在一起,分工是:
//
//   按键回调(button 组件的 esp_timer 任务)只做三件不阻塞的事:过按键守卫、
//     翻译成语义键入队,以及熄屏时"把屏幕点亮"。不碰 LVGL、不读 NVS、不读 I2C。
//   LVGL 定时器(100ms,跑在 LVGL 任务里,已持锁)消化队列、推进模型、刷新界面、
//     按需落盘、触发提示音 —— 也就是说模型只在这一个任务里被修改。
//   功耗任务(独立)负责调暗 / 熄屏 / 自动休眠、电量轮询,以及最终的深睡流程。
//     它读模型状态时读的是一个 volatile 镜像,不直接读模型。
#pragma once

#include "esp_err.h"

// 读取本次的唤醒原因;若是按键唤醒,武装按键守卫(吞掉唤醒键那一次动作)。
//
// 越早调用越好:必须在显示初始化这类要几百毫秒的步骤【之前】。按键组件一旦启动
// 就会看到一个"已经按下"的电平,并在按住达到门限时判成长按、立刻触发一次动作 ——
// 守卫晚一步武装就拦不住它。
void focus_app_guard_wakeup(void);

// 启动应用。要求 display 与 LVGL 已初始化完成。
//
// 会自行初始化 NVS(读回上次状态)、按键、音频与电量计;音频与电量计失败只降级
// (没有提示音 / 顶栏显示 "--"),不阻塞启动。成功可重复调用。
// 返回非 ESP_OK 表示界面可能已经建起来但没法操作(例如按键初始化失败)。
esp_err_t focus_app_start(void);
